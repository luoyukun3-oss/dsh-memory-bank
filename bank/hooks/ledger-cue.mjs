// ============================================================================
// Memory Bank · hooks/ledger-cue —— 「记账指令」检测（2026-10-27 用户拍板「全做」时落地）
//
// 起因：用户 2026-10-26 说「以后出错直接塞进收件箱」，但当天两次都是**他提醒我才做**。
// 病的地方不是"不知道规则"，是"那一刻想不起来" —— 同族教训：2026-10-15「写进教训页 ≠ 会被触发」。
// ⇒ 这里做一层**纯词表检测**：提问里出现「记账动词 + 记账对象」就直接注入一句提醒。
//    不依赖自觉、不改任何用户可见的界面，只是多一段上下文。
//
// ⚠️ 判据刻意保守：只认「动词 + 对象」的组合，或明确的文件名（`inbox.md`），
//    避免把日常聊天里的「这是个教训」也当成指令。
//    误报的代价 = 白提醒一句；漏报的代价 = 又靠用户催 —— 所以宁可稍微宽一点，但必须卡住裸的「教训」。
// ============================================================================

const VERBS = '(?:塞进|塞到|记进|记到|写进|写到|放进|放到|加进|加到|落进|落盘|存进|存入)';
const OBJS = '(?:教训箱|教训收件箱|教训页|收件箱|inbox|台账)';
/** 动词 + （≤8 字） + 对象 —— 例如「塞进教训收件箱」「记进收件箱」「落盘到教训页」 */
const RE_PAIR = new RegExp(VERBS + '[^。\\n]{0,8}' + OBJS, 'i');
/** 点名文件，例如「写进 inbox.md」「收件箱.md 里加一条」 */
const RE_NAMED = /(?:inbox|收件箱)\.md/i;

/** 命中「记账指令」→ 返回一句提醒；否则返回 ''（不占注入预算）。 */
export function ledgerCue(prompt = '') {
  const s = String(prompt || '');
  if (!s.trim()) return '';
  if (!RE_PAIR.test(s) && !RE_NAMED.test(s)) return '';
  return '【记账提醒】这条像是在要求**把某个错误/结论落盘** —— 按 2026-10-26 的拍板：'
    + '先写 `inbox.md`（`cli remember "<要点>" --page inbox.md`），再做别的；'
    + '写完不必汇报，但别只在嘴上答应。';
}
