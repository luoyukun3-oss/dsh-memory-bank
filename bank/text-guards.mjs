/**
 * 剥掉正文开头的「今天」日期。
 *
 * 起因：`cli.mjs remember` 写入时统一加 `- ${day()} ` 前缀；调用者若在正文开头又写了
 * 一遍**当天**日期，结果就是 `- 2026-09-28 2026-09-28 …`。此错在 09-23 / 09-24 / 09-28
 * 复发过三次（lessons 里记了两次「别再手写日期」）⇒ **靠记性没用，做成机制**。
 * 加它之前实测全库已有 7 处（分布在 5 个页，2026-09-29 一次性修掉）。
 *
 * ⚠️ **只剥与 `today` 相同**的日期：
 *   · 「今天」是重复前缀的唯一成因 ⇒ 剥它精准、零误伤；
 *   · 写「昨天 / 历史某天」是**有意为之**（记旧事），剥掉会让日期失真 ⇒ 不动。
 * 剥完为空（正文只有一个日期）时返回空串，由调用方决定怎么处理。
 *
 * @param {string} text  原始正文
 * @param {string} today `YYYY-MM-DD` 形态的当天日期
 * @returns {string}
 */
export const stripOwnDate = (text, today) => {
  const s = String(text || '');
  const t = String(today || '');
  if (!t || !s.startsWith(t)) return s;
  return s.slice(t.length).replace(/^[\s:：]+/, '');
};
