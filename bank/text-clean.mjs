// Memory Bank · text-clean —— 检索前的口语清洗（2026-09-30 新增）
//
// 为什么要有它：中文 bigram 分词（core.mjs 的 tokenize）会把口语疑问词也切碎成二元组 ——
// 「成考什么时候报名」会产出 `时候`/`候报`，而 `时候` 在几乎每条流水里都出现 ⇒ 它既抬高
// 覆盖率分母、又给所有文档加分（噪声地板被顶高）。检索要的是实词，不是寒暄。
//
// 学自 AAAAGENT 的 `memory/dynamics-cues.ts`（见 `refs-memory-design.md` 第 3 节），
// 原则照抄它的原话：**「Fixed, inspectable lexical rules」** —— 不让模型参与打分，
// 必须**可预测、可复现**。它的做法是先剥一个口语停用词正则、再切 bigram；
// 我们做同一件事，只是词表用数组（可 grep、可增删、可单测）。
//
// ⚠️ 两条自我约束（想清楚了才写下来，别下次手抖扩大词表）：
//   ① **只剥 2 字以上的功能性词，不剥单字** —— 剥 `了`/`的`/`过` 会破坏词边界
//      （「了解」→「解」），bigram 场景下是净损失。
//   ② **不照搬 core.mjs 的 STOP 表** —— 那张表是为 reflect 的「高频话题」而设的，含
//      `python`/`print`/`问题`/`方法` 这类**检索里有意义**的词；照搬会让
//      「我学 Python 学到哪了」丢掉唯一的实词。这里只收疑问 / 寒暄 / 填充。
// ============================================================================

/** 口语停用词：命中即整块换成空格，不参与 bigram。长词内含短词，故必须先剥长的。 */
const CJK_FILLER = [
  '什么时候', '什么地方', '为什么', '什么样', '怎么样', '怎么办', '怎么回事',
  '可不可以', '是不是', '有没有', '能不能', '要不要', '好不好', '行不行', '对不对',
  '告诉我', '帮我看看', '帮我查', '帮我找', '介绍一下', '讲一下', '说一下',
  '什么', '怎么', '哪些', '哪个', '多少', '一下', '帮我', '看看', '说说', '讲讲',
  '记得', '还有', '以及', '之类', '什么的',
];

// 长词优先：`什么时候` 必须早于 `什么` —— 否则先剥掉 `什么` 会留下孤零零的 `时候`（正是要治的东西）。
const SORTED = [...CJK_FILLER].sort((a, b) => b.length - a.length);

/** 把口语停用词整块换成空格。用 split/join 而不是正则：词表里就算出现正则元字符也不会炸。 */
export function stripFillers(text) {
  let s = String(text || '');
  for (const w of SORTED) if (s.includes(w)) s = s.split(w).join(' ');
  return s;
}

